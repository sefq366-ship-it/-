def guess_father_name(otchestvo: str):
    key = otchestvo.strip().lower()
    return OTCHESTVO_TO_NAME.get(key)

@dp.message(Command("start"))
async def cmd_start(message: Message):
    await message.answer(
        "Привет! Напиши отчество (например: Иванович), "
        "и я скажу, как зовут твоего отца."
    )

@dp.message(F.text)
async def handle_text(message: Message):
    text = message.text.strip()
    name = guess_father_name(text)
    if name:
        await message.answer(f"Твоего отца зовут: {name}")
    else:
        await message.answer(
            "Не знаю такого отчества 🤔\n"
            "Попробуй в форме: Иванович / Ивановна"
        )

